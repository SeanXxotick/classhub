// Turns the Android app's vector icons (app/src/main/res/drawable/ic_*.xml) into src/ui/iconData.ts,
// so the web app draws exactly the same icons. Run from web/: node scripts/gen-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join('..', 'app', 'src', 'main', 'res', 'drawable');
const icons = {};
for (const file of readdirSync(dir).filter((f) => /^ic_(kind|sched|tab|my)_.*\.xml$/.test(f))) {
  const xml = readFileSync(join(dir, file), 'utf8');
  const size = Number(/android:viewportWidth="([\d.]+)"/.exec(xml)[1]);
  const paths = [...xml.matchAll(/<path([\s\S]*?)\/>/g)].map(([, attrs]) => {
    const get = (name) => new RegExp(`android:${name}="([^"]*)"`).exec(attrs)?.[1];
    return {
      d: get('pathData'),
      stroke: get('strokeColor') ? true : undefined,
      fill: get('fillColor') ? true : undefined,
      width: get('strokeWidth') ? Number(get('strokeWidth')) : undefined,
    };
  });
  icons[file.replace(/\.xml$/, '')] = { size, paths };
}
const out =
  '// Generated by scripts/gen-icons.mjs from the Android app\'s vector icons. Do not edit by hand.\n' +
  'export interface IconPath { d: string; stroke?: boolean; fill?: boolean; width?: number }\n' +
  'export const ICONS: Record<string, { size: number; paths: IconPath[] }> = ' +
  JSON.stringify(icons, null, 1) +
  ';\n';
writeFileSync(join('src', 'ui', 'iconData.ts'), out);
console.log(Object.keys(icons).length, 'icons');
